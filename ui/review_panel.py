ACTIONS = ["Pending", "Accept", "Reject", "Edit"]
LEVELS = ["High", "Medium", "Low"]


def _user() -> str:
    return st.session_state.get("username") or "unknown"


def _key(run_id: str, *parts) -> str:
    return "rv_" + "_".join([run_id, *map(str, parts)])


def _drafts(run_id: str) -> dict:
    return st.session_state.setdefault("review_drafts", {}).setdefault(run_id, {})


def _init(key: str, value) -> str:
    """Give a widget its starting value through session_state only (passing
    value= as well makes Streamlit warn when Regenerate pre-fills it)."""
    if key not in st.session_state:
        st.session_state[key] = value
    return key


def _mandatory_reasons(payload: dict) -> dict:
    return {(i["type"], i["id"]): i["reasons"] for i in payload.get("mandatory", [])}


def _regenerate(kind: str, run_id: str, item_id: str, comment: str) -> None:
    lock = get_run_lock()
    if not lock.acquire(blocking=False):
        st.warning("The agents are busy with another run. Try again in a moment.")
        return
    try:
        with st.spinner(f"🤔 Regenerating {item_id}… (up to a few minutes on this laptop)", show_time=True):
            state = pipeline.run_state(run_id)
            new = (regenerate.regenerate_requirement if kind == "requirement"
                   else regenerate.regenerate_mapping)(state, item_id, comment)
    finally:
        lock.release()
    if new is None:
        st.error("The model's answer could not be used. Edit the item by hand or try again.")
        return
    _drafts(run_id)[(kind, item_id)] = new
    st.session_state[_key(run_id, kind, item_id, "action")] = "Edit"
    if kind == "requirement":
        st.session_state[_key(run_id, kind, item_id, "statement")] = new["statement"]
        st.session_state[_key(run_id, kind, item_id, "ac")] = "\n".join(
            f"{c['given']} | {c['when']} | {c['then']}" for c in new["acceptance_criteria"])
    else:
        kb_ids = [cid for cid, c in (pipeline.run_state(run_id).get("chunk_map") or {}).items()
                  if c.get("origin") == "kb"]
        st.session_state[_key(run_id, kind, item_id, "rules")] = [r for r in new["applicable_rules"]
                                                                  if r in kb_ids]
        for field in ("required_controls", "compliance_gaps"):
            st.session_state[_key(run_id, kind, item_id, field)] = "\n".join(new[field])
    st.rerun()


# --------------------------------------------------- requirements review --
def _requirement_editor(run_id: str, r: dict, mandatory: list[str] | None) -> None:
    allowed = rbac.can_decide_requirement(_user(), mandatory)
    badge = f" · 🔒 mandatory ({'; '.join(mandatory)})" if mandatory else ""
    review = " · ⚠️ needs review" if r.get("needs_human_review") else ""
    with st.expander(f"{r['id']} · {r['confidence']:.2f}{review}{badge} — {r['statement']}"):
        st.markdown(" ".join(f":blue-badge[{c}]" for c in r["categories"])
                    + f" :gray-badge[priority {r['priority']}] :gray-badge[risk {r['risk_level']}]")
        if r.get("flags"):
            st.caption("Flags: " + "; ".join(f"{f['type']}: {f['detail']}" for f in r["flags"]))
        if not allowed:
            needed = rbac.missing_roles_for(_user(), mandatory or []) or ["a reviewer role"]
            st.caption(f"🔐 You can't decide this item – it needs: {', '.join(needed)}.")
        action = st.radio("Decision", ACTIONS, horizontal=True, disabled=not allowed,
                          key=_key(run_id, "requirement", r["id"], "action"))
        st.text_input("Comment (optional)", key=_key(run_id, "requirement", r["id"], "comment"))
        if action == "Edit":
            draft = _drafts(run_id).get(("requirement", r["id"]))
            if draft:
                if draft["statement"].strip() == r["statement"].strip():
                    st.warning("🔄 The model returned the same statement – edit it by hand or try a "
                               "clearer instruction.")
                else:
                    st.info("🔄 Regenerated by the model – check it, change it if needed, then submit.")
                if draft.get("flags"):
                    st.caption("Checks on the new version: " + "; ".join(f["type"] for f in draft["flags"]))
            base = draft or r

            def k(field):
                return _key(run_id, "requirement", r["id"], field)
            st.text_area("Statement", key=_init(k("statement"), base["statement"]))
            left, mid, right = st.columns(3)
            left.selectbox("Priority", LEVELS, key=_init(k("priority"), base["priority"]))
            mid.selectbox("Risk", LEVELS, key=_init(k("risk"), base["risk_level"]))
            right.multiselect("Categories", config.REQUIREMENT_CATEGORIES,
                              key=_init(k("categories"), base["categories"]))
            st.text_area("Acceptance criteria (one per line: given | when | then)",
                         key=_init(k("ac"), "\n".join(f"{c['given']} | {c['when']} | {c['then']}"
                                                     for c in base["acceptance_criteria"])))
        regen_comment = st.text_input("Instruction for regeneration (optional)",
                                      key=_key(run_id, "requirement", r["id"], "regen"))
        if st.button("🔄 Regenerate this requirement", key=_key(run_id, "requirement", r["id"], "regen_btn"),
                     disabled=not allowed):
            _regenerate("requirement", run_id, r["id"], regen_comment)


def _mapping_editor(run_id: str, m: dict, kb_ids: list[str], mandatory: list[str] | None) -> None:
    allowed = rbac.can(_user(), "approve_mapping")
    badge = " · 🔒 compliance-officer approval" if m.get("requires_compliance_officer_approval") else ""
    with st.expander(f"{m['requirement_id']} · impact {m['impact']}{badge}"):
        st.markdown(f"**Rules:** {', '.join(m['applicable_rules']) or '—'}  \n"
                    f"**Controls:** {'; '.join(m['required_controls']) or '—'}  \n"
                    f"**Gaps:** {'; '.join(m['compliance_gaps']) or '—'}")
        if m.get("flags"):
            st.caption("Flags: " + "; ".join(f"{f['type']}: {f['detail']}" for f in m["flags"]))
        if not allowed:
            st.caption("🔐 Only a compliance officer can decide compliance mappings.")
        action = st.radio("Decision", ACTIONS, horizontal=True, disabled=not allowed,
                          key=_key(run_id, "mapping", m["requirement_id"], "action"))
        st.text_input("Comment (optional)", key=_key(run_id, "mapping", m["requirement_id"], "comment"))
        if action == "Edit":
            base = _drafts(run_id).get(("mapping", m["requirement_id"])) or m
            st.multiselect("Applicable rules (knowledge-base excerpts only)", kb_ids,
                           key=_init(_key(run_id, "mapping", m["requirement_id"], "rules"),
                                     [r for r in base["applicable_rules"] if r in kb_ids]))
            for field, label in (("required_controls", "Required controls"), ("compliance_gaps", "Gaps")):
                st.text_area(f"{label} (one per line)",
                             key=_init(_key(run_id, "mapping", m["requirement_id"], field), "\n".join(base[field])))
        regen_comment = st.text_input("Instruction for regeneration (optional)",
                                      key=_key(run_id, "mapping", m["requirement_id"], "regen"))
        if st.button("🔄 Regenerate this mapping", key=_key(run_id, "mapping", m["requirement_id"], "regen_btn"),
                     disabled=not allowed):
            _regenerate("mapping", run_id, m["requirement_id"], regen_comment)


def _lines(text: str) -> list[str]:
    return [line.strip() for line in (text or "").splitlines() if line.strip()]


def collect_requirement_decisions(run_id: str, state: dict) -> dict:
    """Turn the review widgets into the decisions dict for resume_pipeline()."""
    ss = st.session_state
    decisions = {"reviewer": _user(), "requirements": {}, "mappings": {}, "suggested": {}}
    for r in state["agent_outputs"]["requirements_agent"]["parsed"]["requirements"]:
        action = ss.get(_key(run_id, "requirement", r["id"], "action"), "Pending").lower()
        if action == "pending":
            continue
        decision = {"action": action, "comment": ss.get(_key(run_id, "requirement", r["id"], "comment"), "")}
        if action == "edit":
            criteria = []
            for line in _lines(ss.get(_key(run_id, "requirement", r["id"], "ac"), "")):
                parts = [p.strip() for p in line.split("|")] + ["", ""]
                criteria.append(AcceptanceCriterion(given=parts[0], when=parts[1], then=parts[2]).model_dump())
            draft = _drafts(run_id).get(("requirement", r["id"]))
            new = dict(draft) if draft else {}
            new.update(statement=ss.get(_key(run_id, "requirement", r["id"], "statement"), r["statement"]),
                       priority=ss.get(_key(run_id, "requirement", r["id"], "priority"), r["priority"]),
                       risk_level=ss.get(_key(run_id, "requirement", r["id"], "risk"), r["risk_level"]),
                       categories=ss.get(_key(run_id, "requirement", r["id"], "categories"), r["categories"]),
                       acceptance_criteria=criteria or r["acceptance_criteria"])
            decision.update(action="regenerate" if draft else "edit", new=new)
        decisions["requirements"][r["id"]] = decision
    compliance = (state["agent_outputs"].get("compliance_agent") or {}).get("parsed") or {}
    for m in compliance.get("mappings", []):
        rid = m["requirement_id"]
        action = ss.get(_key(run_id, "mapping", rid, "action"), "Pending").lower()
        if action == "pending":
            continue
        decision = {"action": action, "comment": ss.get(_key(run_id, "mapping", rid, "comment"), "")}
        if action == "edit":
            draft = _drafts(run_id).get(("mapping", rid))
            decision.update(action="regenerate" if draft else "edit", new={
                **({k: draft[k] for k in ("evidence", "approval_checkpoints", "retention_reporting_obligations",
                                          "impact")} if draft else {}),
                "applicable_rules": ss.get(_key(run_id, "mapping", rid, "rules"), m["applicable_rules"]),
                "required_controls": _lines(ss.get(_key(run_id, "mapping", rid, "required_controls"), "")),
                "compliance_gaps": _lines(ss.get(_key(run_id, "mapping", rid, "compliance_gaps"), ""))})
        decisions["mappings"][rid] = decision
    for s in compliance.get("suggested_requirements", []):
        choice = ss.get(_key(run_id, "suggested", s["id"]), "Pending")
        if choice != "Pending":
            decisions["suggested"][s["id"]] = "accept" if choice == "Add as requirement" else "reject"
    return decisions


def _requirements_review(result) -> None:
    run_id = result.run_id
    state = pipeline.run_state(run_id)
    reasons = _mandatory_reasons(result.review_payload)
    requirements = state["agent_outputs"]["requirements_agent"]["parsed"]["requirements"]
    compliance = (state["agent_outputs"].get("compliance_agent") or {}).get("parsed") or {}

    st.subheader("✋ Review 1 of 2 · requirements and compliance mappings")
    st.caption("Accept, reject or edit each item (Regenerate asks the model for a new version, "
               "which you then check). Items left Pending stay pending. 🔒 marks items that must "
               "be decided before a baseline can be locked.")
    if st.button("✔️ Set every Pending requirement and mapping to Accept"):
        for r in requirements:
            key = _key(run_id, "requirement", r["id"], "action")
            if st.session_state.get(key, "Pending") == "Pending":
                st.session_state[key] = "Accept"
        for m in compliance.get("mappings", []):
            key = _key(run_id, "mapping", m["requirement_id"], "action")
            if st.session_state.get(key, "Pending") == "Pending":
                st.session_state[key] = "Accept"
        st.rerun()

    st.markdown("#### Requirements")
    for r in requirements:
        _requirement_editor(run_id, r, reasons.get(("requirement", r["id"])))
    if compliance.get("mappings"):
        st.markdown("#### Compliance mappings")
        st.caption(compliance.get("disclaimer", ""))
        kb_ids = [cid for cid, c in (state.get("chunk_map") or {}).items() if c.get("origin") == "kb"]
        for m in compliance["mappings"]:
            _mapping_editor(run_id, m, kb_ids, reasons.get(("mapping", m["requirement_id"])))
    if compliance.get("suggested_requirements"):
        st.markdown("#### Suggested security / privacy requirements")
        for s in compliance["suggested_requirements"]:
            st.radio(f"**{s['id']}** — {s['statement']}", ["Pending", "Add as requirement", "Reject"],
                     horizontal=True, key=_key(run_id, "suggested", s["id"]),
                     disabled=not rbac.can(_user(), "decide_suggestion"))

    st.caption("Items you can't decide stay pending; colleagues with the right role can decide them "
               "after the run (🔒 Mandatory approvals section).")
    if st.button("✅ Submit review and continue", type="primary", width="stretch"):
        allowed, denied = rbac.filter_requirement_decisions(
            collect_requirement_decisions(run_id, state), result.review_payload.get("mandatory", []),
            _user(), run_id)
        if denied:
            st.session_state["review_denied"] = denied
        _queue_resume(run_id, allowed)


def _sdlc_review(result) -> None:
    from ui.results import show_sdlc
    run_id = result.run_id
    sdlc = result.get("sdlc_agent")
    st.subheader("✋ Review 2 of 2 · SDLC selection")
    st.caption("🔒 Mandatory: the SDLC choice needs human approval (Phase 7 will require the project "
               "manager, architect, security and compliance roles to approve jointly).")
    if sdlc and sdlc.parsed:
        with st.container(border=True):
            show_sdlc(sdlc, result)
        models = [r.model for r in sdlc.parsed.ranking]
    else:
        st.warning("The SDLC Agent produced no result.")
        models = []
    recommended = sdlc.parsed.recommended_model if sdlc and sdlc.parsed else ""
    votes = projects.sdlc_votes(run_id)
    st.markdown("**Joint approval – one vote per role**")
    st.dataframe(pd.DataFrame([{"Role": rbac.ROLE_LABELS[role],
                                "Vote": (f"{votes[role]['action']} ({votes[role]['model'] or recommended})"
                                         if role in votes else "⏳ waiting"),
                                "By": votes[role]["user"] if role in votes else "",
                                "Comment": votes[role]["comment"] if role in votes else ""}
                               for role in rbac.SDLC_JOINT_ROLES]), hide_index=True, width="stretch")
    can_vote = rbac.can(_user(), "vote_sdlc")
    if not can_vote:
        st.caption("🔐 Only a project manager, architect, security officer or compliance officer can vote.")
    choice = st.radio("Your vote", ["Approve the recommendation", "Choose another model", "Reject"],
                      horizontal=True, key=_key(run_id, "sdlc", "action"), disabled=not can_vote)
    other = st.selectbox("Model", models[1:], key=_key(run_id, "sdlc", "model"),
                         disabled=choice != "Choose another model" or not can_vote)
    comment = st.text_input("Comment / justification", key=_key(run_id, "sdlc", "comment"), disabled=not can_vote)
    if st.button("🗳️ Submit my vote", type="primary", width="stretch", disabled=not can_vote):
        action = {"Approve the recommendation": "approve", "Choose another model": "override",
                  "Reject": "reject"}[choice]
        projects.record_sdlc_vote(run_id, _user(), action, other if action == "override" else recommended, comment)
        decision = projects.sdlc_joint_decision(run_id, recommended)
        if decision is None:
            st.rerun()                       # waiting for the other roles
        _queue_resume(run_id, decision)


def _queue_resume(run_id: str, decisions: dict) -> None:
    st.session_state["resume_request"] = {"run_id": run_id, "decisions": decisions}
    st.session_state["running"] = True
    st.rerun()


def render_review(result) -> None:
    with st.container(border=True):
        if result.review_stage == "requirements_review":
            _requirements_review(result)
        elif result.review_stage == "sdlc_review":
            _sdlc_review(result)


# ----------------------------------------------------------- baseline panel --
def state_from_result(result) -> dict:
    """A minimal state dict (as the review/baseline code expects) from a result."""
    return {"run_id": result.run_id, "scenario": result.scenario, "chunk_map": result.chunk_map,
            "agent_outputs": {r.key: {"parsed": r.parsed.model_dump() if r.parsed else None}
                              for r in result.agent_results}}


def render_baseline_panel(result) -> None:
    state = state_from_result(result)
    st.markdown("#### 🔒 Mandatory approvals")
    items = mandatory_items(state)
    blocking = {(b["type"], b["id"]) for b in blocking_items(state)}
    if items:
        st.dataframe(pd.DataFrame([{"Item": i["id"], "Type": i["type"], "Why mandatory": "; ".join(i["reasons"]),
                                    "Status": i["status"],
                                    "Decided": "⏳ no" if (i["type"], i["id"]) in blocking else "✅ yes"}
                                   for i in items]), hide_index=True, width="stretch")
    if result.review_mode == "interactive":
        _pending_decisions(result, state)
    existing = baselines.baselines_for_run(result.run_id)
    project = projects.run_project(result.run_id)
    can_lock = rbac.can(_user(), "lock_baseline")
    if not can_lock:
        st.caption("🔐 Only a project manager can lock a baseline.")
    if st.button("🔒 Lock requirements baseline", type="primary", disabled=bool(blocking) or not can_lock,
                 help="Possible once every mandatory item is decided."):
        try:
            baseline = baselines.lock_baseline(state, _user(), project)
            st.success(f"Baseline v{baseline['version']} locked ({len(baseline['content']['requirements'])} "
                       f"approved requirements, hash {baseline['content_hash']}).")
            existing = baselines.baselines_for_run(result.run_id)
        except baselines.BaselineError as error:
            st.error(str(error))
    if blocking:
        st.caption(f"{len(blocking)} mandatory item(s) still need a decision.")

    all_versions = baselines.baselines_for(project)
    if not all_versions:
        return
    st.markdown("#### Baselines")
    st.dataframe(pd.DataFrame([{"Version": b["version"], "Run": b["run_id"], "By": b["created_by"],
                                "When": b["created_at"][:16].replace("T", " "),
                                "Requirements": len(b["content"]["requirements"]), "Hash": b["content_hash"],
                                "Note": b["note"]} for b in all_versions]), hide_index=True, width="stretch")

    latest = all_versions[0]
    with st.expander("✏️ Request a change to an approved requirement (needs re-approval)"):
        ids = [r["id"] for r in latest["content"]["requirements"]]
        rid = st.selectbox("Requirement (latest baseline v%d)" % latest["version"], ids, key="cr_req")
        current = next(r for r in latest["content"]["requirements"] if r["id"] == rid)
        new_statement = st.text_area("New statement", value=current["statement"], key=f"cr_text_{rid}")
        reason = st.text_input("Reason", key="cr_reason")
        if st.button("Submit change request", disabled=not rbac.can(_user(), "request_change")):
            try:
                cr = baselines.request_change(latest["id"], rid, {"statement": new_statement}, reason, _user())
                st.success(f"Change request #{cr} submitted.")
            except baselines.BaselineError as error:
                st.error(str(error))

    pending = baselines.change_requests("pending", project)
    can_decide = rbac.can(_user(), "decide_change_request")
    if pending:
        st.markdown("#### Pending change requests")
        for cr in pending:
            with st.container(border=True):
                st.markdown(f"**#{cr['id']} · {cr['requirement_id']}** (baseline v{cr['baseline_version']}) "
                            f"by {cr['requested_by']} — {cr['reason'] or 'no reason given'}")
                st.markdown(f"- Before: {cr['before']['statement']}\n- After: {cr['after']['statement']}")
                left, right = st.columns(2)
                if left.button("Approve (new baseline version)", key=f"cr_ok_{cr['id']}", disabled=not can_decide):
                    new = baselines.decide_change_request(cr["id"], True, _user())
                    st.success(f"Approved – baseline v{new['version']} created.")
                    st.rerun()
                if right.button("Reject", key=f"cr_no_{cr['id']}", disabled=not can_decide):
                    baselines.decide_change_request(cr["id"], False, _user())
                    st.rerun()


def _pending_decisions(result, state: dict) -> None:
    """After the run: users with the right role decide items still pending
    (e.g. mappings that only a compliance officer may approve)."""
    reasons = {(i["type"], i["id"]): i["reasons"] for i in mandatory_items(state)}
    requirements = [r for r in ((state["agent_outputs"].get("requirements_agent") or {}).get("parsed") or {})
                    .get("requirements", []) if r["approval_status"] == "pending"]
    mappings = [m for m in ((state["agent_outputs"].get("compliance_agent") or {}).get("parsed") or {})
                .get("mappings", []) if m["approval_status"] == "pending"]
    if not requirements and not mappings:
        return
    with st.expander(f"⏳ {len(requirements) + len(mappings)} item(s) still pending – decide them here"):
        decisions = {"requirements": {}, "mappings": {}}
        for r in requirements:
            allowed = rbac.can_decide_requirement(_user(), reasons.get(("requirement", r["id"])))
            choice = st.radio(f"{r['id']}: {r['statement']}", ["Pending", "Accept", "Reject"], horizontal=True,
                              key=_key(result.run_id, "post", "req", r["id"]), disabled=not allowed)
            if choice != "Pending":
                decisions["requirements"][r["id"]] = {"action": choice.lower()}
        for m in mappings:
            choice = st.radio(f"Mapping {m['requirement_id']} (impact {m['impact']})", ["Pending", "Accept", "Reject"],
                              horizontal=True, key=_key(result.run_id, "post", "map", m["requirement_id"]),
                              disabled=not rbac.can(_user(), "approve_mapping"))
            if choice != "Pending":
                decisions["mappings"][m["requirement_id"]] = {"action": choice.lower()}
        if st.button("Save these decisions", key=_key(result.run_id, "post", "save")):
            allowed, denied = rbac.filter_requirement_decisions(decisions, mandatory_items(state), _user(),
                                                                result.run_id)
            st.session_state["result"] = pipeline.apply_post_run_decisions(result.run_id, allowed)
            if denied:
                st.warning("Not allowed for your roles: " + ", ".join(denied))
            st.rerun()
